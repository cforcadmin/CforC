/**
 * ΤΟ ΠΕΡΙΘΩΡΙΟ ΓΙΑ ΤΗΝ ΠΡΩΤΗ ΜΕΤΑΓΛΩΤΤΙΣΗ.
 *
 * 24/10/2026: τρία tests «απέτυχαν» ενώ η λειτουργία δούλευε. Ο dev server
 * του Next μεταγλωττίζει κάθε διαδρομή στο ΠΡΩΤΟ χτύπημα, και το log του το
 * λέει καθαρά:
 *
 *   GET /members/katiana-houli 200 in 5.4s (compile: 4.8s, render: 603ms)
 *
 * Η προεπιλογή του Playwright για assertions είναι 5000ms. Αστόχησε κατά
 * 400 χιλιοστά του δευτερολέπτου.
 *
 * Το ύπουλο: στο ΔΕΥΤΕΡΟ τρέξιμο η διαδρομή είναι ήδη μεταγλωττισμένη, οπότε
 * το test αποτυγχάνει ΑΛΛΟΥ ή περνάει — μοιάζει με αστάθεια ενώ είναι
 * ντετερμινιστικό κόστος πρώτης επίσκεψης.
 *
 * ΔΕΝ ανεβάζουμε το καθολικό όριο: αυτό θα έκρυβε πραγματική βραδύτητα
 * παντού. Μπαίνει ΜΟΝΟ στα σημεία που πληρώνουν την πρώτη μεταγλώττιση.
 */
export const DEV_COMPILE = 20_000

/**
 * Περιμένει να φανεί το στοιχείο, ΧΩΡΙΣ να σκάει αν δεν υπάρχει.
 *
 * Υπάρχει για τα tests που γράφουν `if (await x.isVisible())`: το
 * `isVisible()` ΔΕΝ περιμένει — απαντά αμέσως. Σκέτη αφαίρεση της
 * αναμονής θα έκανε το `if` ψευδές και το test θα περνούσε χωρίς να
 * ελέγξει τίποτα, που είναι χειρότερο από το να αποτυγχάνει.
 */
export async function appeared(locator: Locator, timeout = 15_000): Promise<boolean> {
  try {
    await locator.waitFor({ state: 'visible', timeout })
    return true
  } catch {
    return false
  }
}

/** Η σελίδα απέδωσε: υπάρχει επικεφαλίδα. Αντικαθιστά το «περίμενε δίκτυο». */
export async function rendered(page: Page, timeout = 15_000): Promise<void> {
  await page.locator('h1, h2').first().waitFor({ state: 'visible', timeout })
}
