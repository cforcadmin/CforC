/**
 * Ο κανόνας που δεν σπάει ποτέ: καμία πληρωμή πριν από την έκδοση.
 * Το περιστατικό (1/9/2026): νέο τιμολόγιο Κληρονόμου 74,40 € της 29/8 πήρε
 * την πληρωμή 10/8 — που ανήκε στο τιμολόγιο του Ιουλίου, ίδιου ποσού.
 */

/** Ίδια συνθήκη με το expense-intake: μια χρέωση μπορεί να πληρώνει ένα
 *  παραστατικό μόνο αν έγινε την ημέρα της έκδοσης ή αργότερα */
const payable = (debitDate: string, issueDate: string | null) =>
  !issueDate || String(debitDate).slice(0, 10) >= String(issueDate).slice(0, 10)

describe('πληρωμή ποτέ πριν από την έκδοση', () => {
  it('απορρίπτει τη χρέωση που προηγείται της έκδοσης', () => {
    expect(payable('2026-08-10', '2026-08-29')).toBe(false)
  })

  it('δέχεται πληρωμή την ίδια μέρα (τραπεζικά έξοδα, αυτόματες χρεώσεις)', () => {
    expect(payable('2026-08-31', '2026-08-31')).toBe(true)
  })

  it('δέχεται πληρωμή σε επόμενο μήνα', () => {
    expect(payable('2026-09-03', '2026-08-29')).toBe(true)
  })

  it('χωρίς ημερομηνία έκδοσης δεν μπλοκάρει — δεν ξέρουμε, δεν μαντεύουμε', () => {
    expect(payable('2026-08-10', null)).toBe(true)
  })

  it('το πραγματικό περιστατικό: 7.9 (31/7) δέχεται 10/8, το 8.9 (29/8) όχι', () => {
    expect(payable('2026-08-10', '2026-07-31')).toBe(true)
    expect(payable('2026-08-10', '2026-08-29')).toBe(false)
  })
})
