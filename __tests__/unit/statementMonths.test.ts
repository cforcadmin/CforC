import { detectStatementMonths, formatMonthEl } from '@/lib/bankStatement'

// Πραγματικές γραμμές myAlpha Web (Αύγουστος 2026, 30/8)
const AUG = `Τίτλος;Κινήσεις Λογαριασμού: GR7101401420142002320005140
Ημερομηνία ; 30/8/2026
Νέο Μικτό Υπόλοιπο:; 30567,26 Π;
Προηγούμενο Μικτό Υπόλοιπο:; 36377,75 Π;

Α/Α;Ημερομηνία;Αιτιολογία;Κατάστημα;Τοκισμός από;Αρ. συναλλαγής;Ποσό;Πρόσημο ποσού;
1;31/08/2026;="ΕΞΟΔΑ INSTANT TRANSF";96;31/8/2026;="202608310960257114";3,50;X;
2;31/08/2026;="ΕΝΤΟΛΗ INSTANT TRANS";96;31/8/2026;="202608310960257114";1174,19;X;
3;31/08/2026;="ΕΞΟΔΑ INSTANT TRANSF";96;31/8/2026;="202608310960261469";3,50;X;
4;31/08/2026;="ΕΝΤΟΛΗ INSTANT TRANS";96;31/8/2026;="202608310960261469";1845,16;X;
`

describe('detectStatementMonths — μήνας αναφοράς vs μήνας επικόλλησης', () => {
  it('βρίσκει τον κυρίαρχο μήνα των κινήσεων', () => {
    expect(detectStatementMonths(AUG)).toEqual(['2026-08'])
  })
  it('κενή επικόλληση → κανένας μήνας (δεν προειδοποιεί)', () => {
    expect(detectStatementMonths('')).toEqual([])
  })
  it('ο κυρίαρχος μήνας πρώτος όταν υπάρχουν ακραίες ημερομηνίες', () => {
    const mixed = AUG + '5;01/09/2026;="ΕΞΟΔΑ";96;1/9/2026;="202609010000000001";1,00;X;\n'
    expect(detectStatementMonths(mixed)[0]).toBe('2026-08')
    expect(detectStatementMonths(mixed)).toContain('2026-09')
  })
  it('ετικέτα μήνα στα ελληνικά', () => {
    expect(formatMonthEl('2026-08')).toBe('Αύγουστος 2026')
    expect(formatMonthEl('bogus')).toBe('bogus')
  })
})
