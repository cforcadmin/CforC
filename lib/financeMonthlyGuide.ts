export interface GuideRenderOptions {
  /** URL εικόνας από το όνομα αρχείου (απόλυτο για email, σχετικό για το site) */
  imageUrl: (file: string) => string
  /** Επιπλέον attributes για το <img> (inline style στο email, class στο site) */
  imgAttrs?: string
  /** Attributes για κάθε <code> (inline style στο email — στο site ντύνεται με CSS) */
  codeAttrs?: string
  /** Η φράση για το {{ADMIN}} */
  adminPhrase: string
}

/** Το html ενός βήματος με τα tokens λυμένα για τον συγκεκριμένο θεατή */
export function renderGuideHtml(html: string, o: GuideRenderOptions): string {
  return html
    .replace(/\[\[IMG:([^|\]]+)\|([^\]]*)\]\]/g, (_m, file: string, alt: string) =>
      `<img src="${o.imageUrl(file)}" alt="${alt}"${o.imgAttrs ? ' ' + o.imgAttrs : ''}>`)
    .replace(/\{\{ADMIN\}\}/g, o.adminPhrase)
    .replace(/<code>/g, o.codeAttrs ? `<code ${o.codeAttrs}>` : '<code>')
}

/** «η/ο Όνομα (Διαχείριση)» όταν ξέρουμε ποιος/ποια κρατά τη θέση Admin */
export function adminPhrase(adminName?: string | null): string {
  return adminName ? `η/ο ${adminName} (Διαχείριση)` : 'η Διαχείριση'
}
