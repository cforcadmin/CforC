/**
 * Ελληνικό κείμενο για συγκρίσεις — μία υλοποίηση, γιατί η σειρά των βημάτων
 * έχει ήδη κοστίσει σφάλματα (1/9/2026):
 *
 *   1. πεζά ΠΡΩΤΑ· το toLowerCase κάνει το τελικό «Σ» → «ς» (U+03C2)
 *   2. τελικό σίγμα → «σ», αλλιώς το «ΔΣ» δεν ταιριάζει ποτέ με «δσ»
 *   3. τόνοι ΠΡΙΝ από τα λατινικά ομοιώματα· αλλιώς το «έ» μένει ελληνικό ενώ
 *      το «ε» γίνεται «e» και οι συγκρίσεις αποτυγχάνουν σιωπηλά
 *
 * Χωρίς εξαρτήσεις: το χρησιμοποιούν και ο server και ο browser.
 */

/** Ελληνικά που μοιάζουν με λατινικά — πιάνει τίτλους γραμμένους ανάμεικτα */
export const GREEK_LOOKALIKES: Record<string, string> = {
  'α': 'a', 'β': 'b', 'ε': 'e', 'ζ': 'z', 'η': 'h', 'ι': 'i', 'κ': 'k',
  'μ': 'm', 'ν': 'v', 'ο': 'o', 'ρ': 'p', 'τ': 't', 'υ': 'u', 'χ': 'x',
}

export function normaliseGreek(s: string): string {
  return String(s || '')
    .toLowerCase()
    .replace(/ς/g, 'σ')
    .normalize('NFD').replace(/[̀-ͯ]/g, '')
    .replace(/[αβεζηικμνορτυχ]/g, c => GREEK_LOOKALIKES[c] ?? c)
    .trim()
}

/**
 * Συνεδρίαση της Συντονιστικής («ΔΣ», «Δ.Σ.») — ΟΧΙ Γενική Συνέλευση:
 * στη ΓΣ παρευρίσκεται όλο το δίκτυο, όχι μόνο οι θέσεις, οπότε δεν έχει
 * νόημα να προσυμπληρωθεί η Συντονιστική.
 */
export function isBoardMeetingTitle(title: string): boolean {
  return /(^|\s)δ\.?σ\.?(\s|$)/.test(normaliseGreek(title))
}
