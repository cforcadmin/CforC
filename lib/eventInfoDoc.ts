/**
 * ΕΓΓΡΑΦΟ Β — για όσους δεν είναι μέλη του CforC.
 *
 * Παράγεται από το Α: κόβονται οι δύο ενότητες των μελών, μαζί με ΟΛΑ τα
 * μπλοκ που ακολουθούν μέχρι την επόμενη επικεφαλίδα. Ο κανόνας είναι «μία
 * ενότητα = η επικεφαλίδα της και ό,τι κρέμεται από αυτήν», ώστε μια
 * μελλοντική παράγραφος να φεύγει μαζί της χωρίς να το θυμηθεί κανείς.
 */
export function infoDocFor(isMember: boolean): Block[] {
  if (isMember) return MIDTERM_INFO_A
  const hidden = new Set<string>(MEMBERS_ONLY_SECTIONS)
  const out: Block[] = []
  let dropping = false
  for (const b of MIDTERM_INFO_A) {
    if (b.type === 'section') dropping = hidden.has(b.title)
    if (!dropping) out.push(b)
  }
  return out
}
